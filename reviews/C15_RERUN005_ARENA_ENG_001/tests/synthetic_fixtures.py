# --------------------------------------------------------------------------
# Synthetic disposable Ed25519 key material (openssl, temporary directory)
# --------------------------------------------------------------------------
def generate_ed25519_keypair(directory: Path, name: str) -> tuple[Path, bytes]:
    """Create a throwaway Ed25519 keypair; return (private_path, public_pem)."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    private = directory / f'{name}.priv.pem'
    public = directory / f'{name}.pub.pem'
    subprocess.run([OPENSSL, 'genpkey', '-algorithm', 'ed25519', '-out', str(private)],
                   check=True, capture_output=True, timeout=30)
    private.chmod(0o600)
    subprocess.run([OPENSSL, 'pkey', '-in', str(private), '-pubout', '-out', str(public)],
                   check=True, capture_output=True, timeout=30)
    public.chmod(0o644)
    return private, public.read_bytes()


def ed25519_sign(private_key: Path, message: bytes, scratch: Path) -> bytes:
    """Sign exact bytes with the throwaway key using the real openssl CLI."""
    scratch = Path(scratch)
    scratch.mkdir(parents=True, exist_ok=True)
    message_path = scratch / 'message.bin'
    signature_path = scratch / 'signature.bin'
    message_path.write_bytes(message)
    subprocess.run([OPENSSL, 'pkeyutl', '-sign', '-rawin', '-inkey', str(private_key),
                    '-in', str(message_path), '-out', str(signature_path)],
                   check=True, capture_output=True, timeout=30)
    return signature_path.read_bytes()


class FakeConnection:
    """Minimal AF_UNIX stand-in that feeds the REAL ``receive_message`` framer.

    ``registration_ipc.receive_message`` is exercised unchanged: bounded read,
    exactly-one-newline framing, JSON object requirement. Only the kernel
    transport is replaced, because the Arena sandbox cannot present the
    enrolled UID996/GID983 peer credential.
    """

    def __init__(self, raw: bytes | None = None, *, payload: dict | None = None):
        if raw is None:
            if payload is None:
                raise ValueError('FakeConnection needs raw bytes or a payload')
            raw = canonical_json_bytes(payload) + b'\n'
        self._buffer = raw
        self._delivered = False

    def recv(self, count: int) -> bytes:
        if self._delivered:
            return b''
        self._delivered = True
        return self._buffer[:count]


class FrozenClock:
    """Deterministic replacement for the ``time`` module inside one module."""

    def __init__(self, start: float):
        self.now = float(start)

    def time(self) -> float:
        return self.now

    def advance(self, seconds: float) -> None:
        self.now += float(seconds)


