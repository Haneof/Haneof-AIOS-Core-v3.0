class SignedExchangeFixture:
    """Drive the REAL Window66 signed response contract end to end.

    Real components (unmodified production code):
      * ``ExchangeBridge`` on a temporary directory: durable request artifact,
        durable ledger, durable response publication.
      * ``RunnerRegistrationAuthority``: real kernel-identity registration for
        this process acting as the Runner.
      * ``SignedResponseAuthority.register`` and ``.dispatch``: the actual
        Window66 envelope issuance and verification logic.
      * ``openssl`` Ed25519 signature verification via ``verify_signature``.

    Synthetic components (privileged host facilities only):
      * the TEST_ONLY enrollment grant (``load_grant`` redirected),
      * the Resident kernel peer credential tuple,
      * the AF_UNIX transport feeding ``receive_message``.

    ``SignedResponseAuthority.__init__`` is bypassed with ``object.__new__``
    because it hard-requires ``os.getuid() == 999`` and a real Operator grant.
    Bypassing the constructor exercises the authorization LOGIC without
    claiming any real UID999 execution.
    """

    KIND = 'round_summary'

    def __init__(self, workdir: Path, *, operation_id: str = 'arena-operation-1',
                 instance_id: str = 'arena-instance-1', epoch: str = 'arena-epoch-1',
                 grant_expires_in: int = 1800, kind: str | None = None,
                 clock: FrozenClock | None = None):
        self.workdir = Path(workdir)
        self.operation_id = operation_id
        self.instance_id = instance_id
        self.epoch = epoch
        self.kind = kind or self.KIND
        self.clock = clock

        self.trust = SyntheticTrustRoot(self.workdir / 'trust-material').install()
        self.grant = self.trust.grant(
            now=int(clock.now) if clock else None,
            expires_at=(int(clock.now) if clock else int(time.time())) + grant_expires_in,
            request_kinds=[self.kind],
            operation_ids=[operation_id],
            instance_id=instance_id,
            run_id='arena-synthetic-run',
            session_id='arena-synthetic-session')
        raw_grant_bytes = self.trust.publish(self.grant)
        # Mirror the real load_grant() semantics exactly: ``_sha256`` is the
        # digest of the canonical enrollment BYTES, added after validation.
        self.grant['_sha256'] = hashlib.sha256(raw_grant_bytes).hexdigest()

        # Redirect the enrollment loader only; register()/dispatch() stay real.
        self._saved_load_grant = response_authorization.load_grant
        response_authorization.load_grant = lambda _path: dict(self.grant)
        self._saved_time = None
        if clock is not None:
            self._saved_time = response_authorization.time
            response_authorization.time = clock

        self.bridge = ExchangeBridge(self.workdir / 'exchange')
        self.runner_pid = os.getpid()
        self.registration_authority = RunnerRegistrationAuthority(
            runner_pid=self.runner_pid, runner_uid=os.getuid(),
            runner_gid=os.getgid(), runner_start_time=process_start_time(self.runner_pid),
            runner_instance_id=instance_id, operation_id=operation_id,
            key_id='arena-synthetic-publisher-key', runner_alive=lambda: True)
        self.runner_peer = (self.runner_pid, os.getuid(), os.getgid())

        self.authority = object.__new__(response_authorization.SignedResponseAuthority)
        self.authority.path = SyntheticTrustRoot.GRANT_PATH
        self.authority.grant = dict(self.grant)
        self.authority.operation_id = operation_id
        self.authority.instance_id = instance_id
        self.authority.epoch = epoch
        self.authority.pending = {}
        self.authority.used = set()
        self.authority.verified_digests = {}
        self.authority.server = None

        self.published_commands: list[dict] = []
        self.marker_dir = self.workdir / 'markers'
        self.marker_dir.mkdir(parents=True, exist_ok=True)

    # -- lifecycle --------------------------------------------------------
    def restore(self) -> None:
        response_authorization.load_grant = self._saved_load_grant
        if self._saved_time is not None:
            response_authorization.time = self._saved_time
            self._saved_time = None
        self.trust.restore()

    # -- request side -----------------------------------------------------
    def publish_request(self, *, run_id: str = 'arena-synthetic-run',
                        session_id: str = 'arena-synthetic-session',
                        subject_id: str = 'arena-synthetic-subject') -> dict:
        body = {'identity': {'run_id': run_id, 'session_id': session_id,
                             'subject_id': subject_id},
                'prompt': 'arena synthetic disposable prompt'}
        return self.bridge.publish_request(kind=self.kind, body=body)

    def register_with_runner(self, record: dict) -> tuple[str, dict]:
        """Register through the REAL Runner registration authority."""
        command = {'command': 'register', 'request_id': record['request_id'],
                   'request_sha256': record['request_sha256'], 'context': None,
                   'core_attempt_id': None, 'runner_instance_id': self.instance_id,
                   'operation_id': self.operation_id}
        rid, registration = self.registration_authority.register(
            self.runner_peer, command, self.bridge)
        return rid, registration

    def arm(self, *, run_id: str = 'arena-synthetic-run',
            session_id: str = 'arena-synthetic-session') -> tuple[str, dict]:
        """Publish a durable request, register it, and issue its challenge."""
        record = self.publish_request(run_id=run_id, session_id=session_id)
        rid, registration = self.register_with_runner(record)
        self.authority.register(rid, registration, self.bridge)
        return rid, record

    # -- response side ----------------------------------------------------
    def response_bytes(self, rid: str, request_sha256: str, *,
                       text: str = 'arena synthetic summary text') -> bytes:
        envelope = {'response_version': 1, 'request_id': rid,
                    'request_sha256': request_sha256,
                    'authored_by': 'EXTERNAL_CURRENT_RESIDENT_SESSION',
                    'directive': {'text': text}}
        return canonical_json_bytes(envelope)

    def signed_command(self, rid: str, record: dict, *, raw: bytes | None = None,
                       mutate=None, private_key: Path | None = None,
                       response_sha256: str | None = None) -> dict:
        """Build a ``publish-signed`` command over the REAL issued envelope."""
        issued = self.authority.pending[rid]['envelope']
        if raw is None:
            raw = self.response_bytes(rid, record['request_sha256'])
        envelope = dict(issued)
        envelope['response_sha256'] = (response_sha256
                                       if response_sha256 is not None
                                       else hashlib.sha256(raw).hexdigest())
        if mutate is not None:
            mutate(envelope)
        key = private_key or self.trust.resident_private
        signature = ed25519_sign(key, canonical_json_bytes(envelope),
                                 self.workdir / 'sign')
        return {'command': 'publish-signed', 'envelope': envelope,
                'signature': signature.hex(),
                'raw': base64.b64encode(raw).decode('ascii')}

    def publish_callback(self):
        """Real durable publication + call recording; also writes a marker."""
        def publish(command, peer):
            self.published_commands.append(command)
            result = self.bridge.responses.publish_bytes(
                request_id=command['request_id'],
                response_bytes=base64.b64decode(command['raw'], validate=True))
            # Emulate the Publisher completion/ACK marker side effect so that a
            # rejected authority can be proven to leave no marker behind.
            (self.marker_dir / f"{command['request_id']}.ack.json").write_bytes(
                canonical_json_bytes({'request_id': command['request_id'],
                                      'response_sha256': result['response_sha256']}))
            return result
        return publish

    def dispatch(self, command: dict, *, peer=SYNTHETIC_RESIDENT_PEER,
                 runner_live: bool = True):
        return self.authority.dispatch(FakeConnection(payload=command), peer,
                                       self.bridge, self.registration_authority,
                                       lambda: runner_live, self.publish_callback())

    def dispatch_raw(self, raw: bytes, *, peer=SYNTHETIC_RESIDENT_PEER,
                     runner_live: bool = True):
        return self.authority.dispatch(FakeConnection(raw), peer, self.bridge,
                                       self.registration_authority,
                                       lambda: runner_live, self.publish_callback())

    # -- assertions helpers ----------------------------------------------
    def credited_anything(self, rid: str) -> dict:
        """Report every side effect that would mean the response was credited."""
        return {
            'publish_calls': len(self.published_commands),
            'response_artifact': self.bridge.responses.path_for(rid).exists(),
            'response_ledger_record': self.bridge.published_response_record(rid) is not None,
            'ack_markers': sorted(p.name for p in self.marker_dir.glob('*.ack.json')),
            'challenge_consumed': rid in self.authority.used,
            'verified_digest': rid in self.authority.verified_digests,
        }


