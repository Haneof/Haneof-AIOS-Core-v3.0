# Synthetic Operator trust root for load_grant()
# --------------------------------------------------------------------------
class SyntheticTrustRoot:
    """Install a purely synthetic, disposable trust root for ``load_grant``.

    ``load_grant`` is exercised byte-for-byte as written: canonical-form
    enforcement, issuer pinning, real Ed25519 signature verification, purpose,
    TEST_ONLY flag, Resident identity, time window, enrollment/instance/scope
    shapes and revocation. Only the four trust anchors that require a
    privileged Operator host are redirected:

    * ``trusted_bytes``   -> serves an in-memory dictionary
    * ``TRUST``           -> a synthetic directory name
    * ``ISSUER_SHA256``   -> the synthetic issuer fingerprint
    * ``RESIDENT_SHA256`` -> the synthetic Resident fingerprint

    The real pinned fingerprints are captured and restored on cleanup, and the
    real ``/var/lib/aios-window65/trust`` tree is never read or written.
    """

    GRANT_PATH = '/synthetic-arena/grant.json'
    SIGNATURE_PATH = '/synthetic-arena/grant.sig'
    REVOCATION_PATH = '/synthetic-arena/revocation.json'

    def __init__(self, workdir: Path):
        self.workdir = Path(workdir)
        self.keys = self.workdir / 'synthetic-keys'
        self.store: dict[str, bytes] = {}
        self.issuer_private, self.issuer_public = generate_ed25519_keypair(self.keys, 'issuer')
        self.resident_private, self.resident_public = generate_ed25519_keypair(self.keys, 'resident')
        self.rogue_private, self.rogue_public = generate_ed25519_keypair(self.keys, 'rogue')
        self.issuer_fingerprint = response_authorization.key_fingerprint(self.issuer_public)
        self.resident_fingerprint = response_authorization.key_fingerprint(self.resident_public)
        self._saved: dict[str, object] = {}

    # -- install / restore ------------------------------------------------
    def install(self) -> 'SyntheticTrustRoot':
        module = response_authorization
        for name in ('trusted_bytes', 'ISSUER_SHA256', 'RESIDENT_SHA256', 'TRUST'):
            self._saved[name] = getattr(module, name)
        module.trusted_bytes = self._trusted_bytes
        module.ISSUER_SHA256 = self.issuer_fingerprint
        module.RESIDENT_SHA256 = self.resident_fingerprint
        module.TRUST = Path('/synthetic-arena/trust')
        self.store[str(module.TRUST / 'issuer.pub')] = self.issuer_public
        self.store[str(module.TRUST / 'resident.pub')] = self.resident_public
        return self

    def restore(self) -> None:
        module = response_authorization
        for name, value in self._saved.items():
            setattr(module, name, value)
        self._saved.clear()
        self.store.clear()

    def _trusted_bytes(self, path) -> bytes:
        key = str(path)
        if key not in self.store:
            raise FileNotFoundError(key)
        return self.store[key]

    # -- grant construction ----------------------------------------------
    def grant(self, *, now: int | None = None, **overrides) -> dict:
        """Build a syntactically valid synthetic TEST_ONLY response grant."""
        moment = int(now if now is not None else time.time())
        value = {
            'domain': 'aios.r005.test.enrollment.v1',
            'version': 1,
            'purpose': response_authorization.PURPOSE,
            'test_only': True,
            'issuer_key_id': self.issuer_fingerprint,
            'enrollment_id': 'W66-' + '0' * 8 + '-' + '0' * 4 + '-' + '0' * 4
                             + '-' + '0' * 4 + '-' + '0' * 12,
            'serial': 'arena-synthetic-serial',
            'issued_at': moment - 10,
            'not_before': moment - 5,
            'expires_at': moment + 1800,
            'resident_id': 'AIOS_RESIDENT_TEST',
            'resident_uid': 996,
            'resident_key_id': self.resident_fingerprint,
            'resident_public_key_pem': self.resident_public.decode('ascii'),
            'run_id': 'arena-synthetic-run',
            'session_id': 'arena-synthetic-session',
            'instance_id': 'a' * 64,
            'operation_ids': ['b' * 64],
            'request_kinds': ['round_summary'],
            'revocation': {'epoch': 7, 'file': self.REVOCATION_PATH},
        }
        value.update(overrides)
        return value

    def publish(self, grant: dict, *, raw: bytes | None = None,
                signature: bytes | None = None,
                revocation: dict | None = None) -> bytes:
        """Serve the grant, its signature and its revocation record."""
        raw_bytes = canonical_json_bytes(grant) if raw is None else raw
        if signature is None:
            signature = ed25519_sign(self.issuer_private, raw_bytes, self.workdir / 'sign')
        self.store[self.GRANT_PATH] = raw_bytes
        self.store[self.SIGNATURE_PATH] = signature
        self.store[self.REVOCATION_PATH] = canonical_json_bytes(
            revocation if revocation is not None
            else {'epoch': grant.get('revocation', {}).get('epoch', 7),
                  'revoked_enrollment_ids': []})
        return raw_bytes

    def load(self, path: str | None = None) -> dict:
        return response_authorization.load_grant(path or self.GRANT_PATH)


